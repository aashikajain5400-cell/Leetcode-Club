/*
 * DATE: 04/11/2026
 *
 * PROBLEM LINK: https://leetcode.com/problems/find-the-difference/
 * PROBLEM STATEMENT:
 * You are given two strings s and t.

    String t is generated by random shuffling string s and then add one more letter at a random position.

    Return the letter that was added to t.

    

    Example 1:

    Input: s = "abcd", t = "abcde"
    Output: "e"
    Explanation: 'e' is the letter that was added.
    Example 2:

    Input: s = "", t = "y"
    Output: "y"
 * __________________________________________________
 * 
 * __________________________________________________
 *
 * INSIGHTS GAIN FROM THIS QUESTION:
 * I used the XOR bitwise operator to find the extra character.
 * XOR of two same characters is always zero.
 * Common characters cancel each other.
 * Only the additional character remains.
 * __________________________________________________
 * 
 * __________________________________________________
 *
 */
#include<iostream>
#include<string>
using namespace std;

class Solution {
public:
    char findTheDifference(string s, string t) {
        char ans = 0;

        for (char c : s) {
            ans ^= c;
        }

        for (char c : t) {
            ans ^= c;
        }

        return ans;
    }
};
int main() {
    Solution solution;
    string s;
    string t;
    cin >> s >> t;
    char result = solution.findTheDifference(s, t);
    cout << result << endl;
    return 0;
}